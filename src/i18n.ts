export const DICTIONARIES: Record<Exclude<UiLang, 'en'>, Dict> = { es, zh };

export function translate(lang: UiLang, key: string, vars?: Record<string, string | number>): string {
  const raw = (lang === 'en' ? undefined : DICTIONARIES[lang][key]) ?? EN[key] ?? key;
  return vars ? raw.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`)) : raw;
}

/** Returns a translation function for the current interface language. */
export function useT() {
  const { data } = useStore();
  const lang = data.settings.uiLang;
  return useCallback((key: string, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang]);
}
