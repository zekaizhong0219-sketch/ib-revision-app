#!/usr/bin/env python3
"""
Builds src/data/voa.generated.ts: transcripts, glossaries and audio links of Voice of America
Learning English stories used for English B listening and reading practice.

VOA states that text, audio and video produced exclusively by VOA are in the public domain.
Only stories written by VOA staff with no wire-service material (AP, Reuters, AFP) are used;
the script refuses a story whose text mentions a wire service.

Usage: python3 scripts/voa_resources.py   (needs curl, beautifulsoup4, lxml)
"""
import json
import pathlib
import re
import subprocess
import sys

from bs4 import BeautifulSoup

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'src' / 'data' / 'voa.generated.ts'
BASE = 'https://learningenglish.voanews.com'

STORIES = {
    # listening
    'wright': '/a/wilbur-and-orville-wright-the-first-airplane/7998765.html',
    'yellowstone': '/a/yellowstone-the-world-s-first-national-park/7974034.html',
    'buck': '/a/pearl-s-buck-the-first-american-woman-to-win-a-nobel-prize-in-literature-/7980858.html',
    'marykay': '/a/mary-kay-a-leader-in-the-beauty-product-industry/7972740.html',
    # reading
    'goddard': '/a/american-inventors-rocket-scientist-robert-goddard/7979682.html',
    'gettysburg': '/a/american-places-gettysburg-pennsylvania/7965779.html',
    'washington': '/a/george-washington-first-president/7972056.html',
}

SKIP = {'Share', 'See comments', 'Follow us', 'Print', 'No media source currently available'}
WIRE = re.compile(r'Associated Press|Reuters|\bAFP\b|Agence France')


def fetch(url: str) -> str:
    r = subprocess.run(['curl', '-sSL', '--fail', '-m', '60', url], capture_output=True)
    if r.returncode != 0:
        sys.exit(f'Could not fetch {url}')
    return r.stdout.decode('utf-8', 'replace')


def story(path: str) -> dict:
    url = BASE + path
    html = fetch(url)
    s = BeautifulSoup(html, 'lxml')
    body = s.select_one('#article-content') or s.select_one('.wsw')
    if body is None:
        sys.exit(f'No article body in {url}')
    paras = [' '.join(p.get_text(' ').split()) for p in body.find_all('p')]
    paras = [p for p in paras if p and p not in SKIP]
    text_all = ' '.join(paras)
    if WIRE.search(text_all):
        sys.exit(f'{url} contains wire-service material; not public domain')
    # Split narrative / credit / glossary at the sign-off ("I'm …") and the underscore rule.
    sign = next((i for i, p in enumerate(paras) if re.match(r"^I[’']m [A-Z][a-z]+ [A-Z]", p)), None)
    if sign is None:
        sys.exit(f'No sign-off in {url}')
    rule = next((i for i, p in enumerate(paras) if set(p) <= {'_'}), len(paras))
    narrative = [re.sub(r' ([,.;:?!])', r'\1', p) for p in paras[: sign + 1]]
    credit = ' '.join(paras[sign + 1 : rule])
    glossary = [p for p in paras[rule + 1 :] if '–' in p or ' - ' in p]
    mp3 = sorted(set(re.findall(r'https://voa-audio\.voanews\.eu/[^"\']+?\.mp3', html)))
    audio = next((m for m in mp3 if m.endswith('_hq.mp3')), mp3[0] if mp3 else None)
    title = ' '.join(s.find('h1').get_text().split())
    t = s.select_one('time')
    date = (t.get('datetime') or '')[:10] if t else ''
    return {'url': url, 'title': title, 'date': date, 'audio': audio, 'credit': credit, 'paragraphs': narrative, 'glossary': glossary}


def main():
    data = {k: story(p) for k, p in STORIES.items()}
    for k, v in data.items():
        words = sum(len(p.split()) for p in v['paragraphs'])
        print(f'{k}: {words} words, audio={"yes" if v["audio"] else "no"}, {v["date"]}')
    OUT.write_text(
        '// Generated by scripts/voa_resources.py. Do not edit by hand.\n'
        '// Voice of America Learning English stories (public domain: produced by VOA staff, no wire-service material).\n'
        'export interface VoaStory { url: string; title: string; date: string; audio: string | null; credit: string; paragraphs: string[]; glossary: string[] }\n\n'
        f'export const VOA_STORIES: Record<string, VoaStory> = {json.dumps(data, ensure_ascii=False, indent=2)};\n',
        encoding='utf-8',
    )
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
